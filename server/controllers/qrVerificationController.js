// Get QR verification history (admin function)
export const getQRVerificationHistory = async (req, res) => {
    try {
        const { page = 1, limit = 20, status, collectorId } = req.query;
        
        const pageNum = parseInt(page);
        const limitNum = parseInt(limit);
        const skip = (pageNum - 1) * limitNum;
        
        const query = { qrCode: { $exists: true, $ne: null } };
        if (status) query.status = status;
        if (collectorId) query.qrVerifiedBy = collectorId;
        
        const pickups = await Pickup.find(query)
            .populate('citizen', 'name email')
            .populate('wasteItem', 'material weight')
            .populate('qrVerifiedBy', 'name email')
            .populate('assignedCollector', 'name email')
            .sort({ qrVerifiedAt: -1, createdAt: -1 })
            .skip(skip)
            .limit(limitNum);
        
        const total = await Pickup.countDocuments(query);
        
        res.json({
            success: true,
            data: {
                pickups,
                pagination: {
                    currentPage: pageNum,
                    totalPages: Math.ceil(total / limitNum),
                    totalItems: total,
                    hasNext: skip + limitNum < total,
                    hasPrev: pageNum > 1
                }
            }
        });
    } catch (error) {
        console.error('Get QR verification history error:', error);
        res.status(500).json({
            success: false,
            message: 'Failed to retrieve verification history',
            error: error.message
        });
    }
};